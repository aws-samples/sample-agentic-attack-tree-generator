#!/usr/bin/env bash

set -Eeuo pipefail
IFS=$'\n\t'
umask 077

# shellcheck source=common.sh
source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)/common.sh"

validate_aws_identity
require_command jq

for stack in \
  ThreatForestFoundation \
  ThreatForestIdentity \
  ThreatForestAgentCore \
  ThreatForestServices \
  ThreatForestWaf \
  ThreatForestEdge \
  ThreatForestEdgeLogging \
  ThreatForestObservability; do
  region="${TF_REGION}"
  [[ "${stack}" == 'ThreatForestWaf' || "${stack}" == 'ThreatForestEdgeLogging' ]] && region="${TF_EDGE_REGION}"
  stack_exists "${stack}" "${region}" || die "Required stack is not deployed: ${stack} (${region})"
done

user_pool_id="$(stack_resource ThreatForestIdentity AWS::Cognito::UserPool UserPool)"
user_pool_client_id="$(stack_resource ThreatForestIdentity AWS::Cognito::UserPoolClient SpaClient)"
distribution_id="$(stack_resource ThreatForestEdge AWS::CloudFront::Distribution Distribution)"
distribution_domain="$(aws_regional cloudfront get-distribution \
  --id "${distribution_id}" --query Distribution.DomainName --output text)"
cognito_domain_prefix="$(aws_regional cognito-idp describe-user-pool \
  --user-pool-id "${user_pool_id}" --query UserPool.Domain --output text)"

artifact_bucket="$(stack_resource ThreatForestFoundation AWS::S3::Bucket ArtifactsBucket)"
state_table="$(stack_resource ThreatForestFoundation AWS::DynamoDB::Table StateTable)"
artifact_key_id="$(stack_resource ThreatForestFoundation AWS::KMS::Key ArtifactsKey)"
state_key_id="$(stack_resource ThreatForestFoundation AWS::KMS::Key StateKey)"
artifact_key_arn="$(aws_regional kms describe-key \
  --key-id "${artifact_key_id}" --query KeyMetadata.Arn --output text)"
state_key_arn="$(aws_regional kms describe-key \
  --key-id "${state_key_id}" --query KeyMetadata.Arn --output text)"

http_api_url="$(stack_output ThreatForestServices HttpApiEndpoint)"
websocket_url="$(stack_output ThreatForestServices WebSocketUrl)"
runtime_arn="$(stack_output ThreatForestAgentCore RuntimeArn)"
runtime_log_group="$(stack_output ThreatForestAgentCore RuntimeLogGroupName)"
memory_id="$(stack_output ThreatForestAgentCore MemoryId)"
gateway_url="$(stack_output ThreatForestAgentCore GatewayUrl)"
evaluation_arn="$(stack_output ThreatForestAgentCore OnlineEvaluationArn)"
evaluation_log_group="$(stack_output ThreatForestAgentCore EvaluationLogGroupName)"
workflow_arn="$(stack_output ThreatForestServices RunWorkflowArn)"
dashboard_name="$(stack_output ThreatForestObservability DashboardName)"
alarm_topic_arn="$(stack_output ThreatForestObservability AlarmTopicArn)"
web_acl_arn="$(stack_resource ThreatForestWaf AWS::WAFv2::WebACL WebAcl "${TF_EDGE_REGION}")"
cloudfront_log_group="$(stack_resource ThreatForestEdgeLogging AWS::Logs::LogGroup CloudFrontAccessLogs "${TF_EDGE_REGION}")"
cloudfront_log_key_id="$(stack_resource ThreatForestEdgeLogging AWS::KMS::Key CloudFrontAccessLogKey "${TF_EDGE_REGION}")"
cloudfront_log_key_arn="$(aws_edge kms describe-key \
  --key-id "${cloudfront_log_key_id}" --query KeyMetadata.Arn --output text)"

output_file="${TF_DEPLOYMENT_ENV_FILE:-${TS_ROOT}/packages/deployed-tests/.env.deployed}"
json_file="${TF_DEPLOYMENT_JSON_FILE:-${TS_ROOT}/packages/deployed-tests/deployment-outputs.json}"
mkdir -p -- "$(dirname -- "${output_file}")" "$(dirname -- "${json_file}")"

{
  printf '# Generated by ts/scripts/deploy/collect-outputs.sh; contains identifiers, not credentials.\n'
  printf 'TF_ACCOUNT_ID=%q\n' "${TF_ACCOUNT_ID}"
  printf 'TF_AWS_PROFILE=%q\n' "${AWS_PROFILE:-}"
  printf 'TF_ENVIRONMENT=%q\n' "${TF_ENVIRONMENT}"
  printf 'TF_REGION=%q\n' "${TF_REGION}"
  printf 'TF_EDGE_REGION=%q\n' "${TF_EDGE_REGION}"
  printf 'TF_BASE_URL=%q\n' "https://${distribution_domain}"
  printf 'TF_HTTP_API_URL=%q\n' "${http_api_url}"
  printf 'TF_WEBSOCKET_URL=%q\n' "${websocket_url}"
  printf 'TF_USER_POOL_ID=%q\n' "${user_pool_id}"
  printf 'TF_USER_POOL_CLIENT_ID=%q\n' "${user_pool_client_id}"
  printf 'TF_COGNITO_DOMAIN=%q\n' "https://${cognito_domain_prefix}.auth.${TF_REGION}.amazoncognito.com"
  printf 'TF_CLOUDFRONT_DISTRIBUTION_ID=%q\n' "${distribution_id}"
  printf 'TF_ARTIFACT_BUCKET=%q\n' "${artifact_bucket}"
  printf 'TF_STATE_TABLE=%q\n' "${state_table}"
  printf 'TF_ARTIFACT_KMS_KEY_ARN=%q\n' "${artifact_key_arn}"
  printf 'TF_STATE_KMS_KEY_ARN=%q\n' "${state_key_arn}"
  printf 'TF_RUNTIME_ARN=%q\n' "${runtime_arn}"
  printf 'TF_RUNTIME_LOG_GROUP=%q\n' "${runtime_log_group}"
  printf 'TF_MEMORY_ID=%q\n' "${memory_id}"
  printf 'TF_GATEWAY_URL=%q\n' "${gateway_url}"
  printf 'TF_EVALUATION_ARN=%q\n' "${evaluation_arn}"
  printf 'TF_EVALUATION_LOG_GROUP=%q\n' "${evaluation_log_group}"
  printf 'TF_WORKFLOW_ARN=%q\n' "${workflow_arn}"
  printf 'TF_DASHBOARD_NAME=%q\n' "${dashboard_name}"
  printf 'TF_ALARM_TOPIC_ARN=%q\n' "${alarm_topic_arn}"
  printf 'TF_WEB_ACL_ARN=%q\n' "${web_acl_arn}"
  printf 'TF_CLOUDFRONT_LOG_GROUP=%q\n' "${cloudfront_log_group}"
  printf 'TF_CLOUDFRONT_LOG_KMS_KEY_ARN=%q\n' "${cloudfront_log_key_arn}"
} >"${output_file}"
chmod 600 "${output_file}"

jq -n \
  --arg accountId "${TF_ACCOUNT_ID}" \
  --arg region "${TF_REGION}" \
  --arg environment "${TF_ENVIRONMENT}" \
  --arg edgeRegion "${TF_EDGE_REGION}" \
  --arg baseUrl "https://${distribution_domain}" \
  --arg httpApiUrl "${http_api_url}" \
  --arg websocketUrl "${websocket_url}" \
  --arg userPoolId "${user_pool_id}" \
  --arg userPoolClientId "${user_pool_client_id}" \
  --arg cognitoDomain "https://${cognito_domain_prefix}.auth.${TF_REGION}.amazoncognito.com" \
  --arg distributionId "${distribution_id}" \
  --arg artifactBucket "${artifact_bucket}" \
  --arg stateTable "${state_table}" \
  --arg artifactKmsKeyArn "${artifact_key_arn}" \
  --arg stateKmsKeyArn "${state_key_arn}" \
  --arg runtimeArn "${runtime_arn}" \
  --arg runtimeLogGroup "${runtime_log_group}" \
  --arg memoryId "${memory_id}" \
  --arg gatewayUrl "${gateway_url}" \
  --arg evaluationArn "${evaluation_arn}" \
  --arg evaluationLogGroup "${evaluation_log_group}" \
  --arg workflowArn "${workflow_arn}" \
  --arg dashboardName "${dashboard_name}" \
  --arg alarmTopicArn "${alarm_topic_arn}" \
  --arg webAclArn "${web_acl_arn}" \
  --arg cloudfrontLogGroup "${cloudfront_log_group}" \
  --arg cloudfrontLogKmsKeyArn "${cloudfront_log_key_arn}" \
  '{
    accountId:$accountId,region:$region,environment:$environment,edgeRegion:$edgeRegion,baseUrl:$baseUrl,
    httpApiUrl:$httpApiUrl,websocketUrl:$websocketUrl,userPoolId:$userPoolId,
    userPoolClientId:$userPoolClientId,cognitoDomain:$cognitoDomain,
    distributionId:$distributionId,artifactBucket:$artifactBucket,stateTable:$stateTable,
    artifactKmsKeyArn:$artifactKmsKeyArn,stateKmsKeyArn:$stateKmsKeyArn,
    runtimeArn:$runtimeArn,runtimeLogGroup:$runtimeLogGroup,memoryId:$memoryId,
    gatewayUrl:$gatewayUrl,evaluationArn:$evaluationArn,
    evaluationLogGroup:$evaluationLogGroup,workflowArn:$workflowArn,
    dashboardName:$dashboardName,alarmTopicArn:$alarmTopicArn,webAclArn:$webAclArn,
    cloudfrontLogGroup:$cloudfrontLogGroup,
    cloudfrontLogKmsKeyArn:$cloudfrontLogKmsKeyArn
  }' >"${json_file}"
chmod 600 "${json_file}"

log "Wrote deployment environment to ${output_file}."
log "Wrote deployment JSON to ${json_file}."
printf '%s\n' "https://${distribution_domain}"
