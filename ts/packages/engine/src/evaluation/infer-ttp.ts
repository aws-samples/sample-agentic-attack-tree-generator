import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { z } from 'zod';
import { MlServiceClient } from '../ml-client.js';
import { selectTtpDecision, TTP_ACCEPTANCE_POLICY_VERSION, CLOUD_TTP_BLOCKLIST } from '../quality/ttp-confidence.js';
import { evaluateTtpQuality, parseTtpEvaluationDataset } from './ttp-quality.js';

const InputSchema = z.object({
  labels: z.record(z.string(), z.unknown()),
  review: z.object({
    status: z.enum(['draft', 'expert_reviewed']),
    reviewer: z.string().trim().min(1).optional(),
    reviewed_at: z.iso.datetime().optional(),
  }).refine(value => value.status !== 'expert_reviewed' || (value.reviewer && value.reviewed_at),
    'Expert-reviewed labels require a reviewer and review date'),
  model: z.string().trim().min(1),
  frameworks: z.array(z.enum(['attack', 'atlas', 'wiz'])).min(1),
}).strict();

/** Predictions are generated by the current service; labels never go to it. */
export async function inferTtpEvaluation(
  input: unknown,
  client: Pick<MlServiceClient, 'matchSteps'> = new MlServiceClient(),
) {
  const parsed = InputSchema.parse(input);
  const rawRecords = z.array(z.record(z.string(), z.unknown())).parse(parsed.labels['records']);
  for (const record of rawRecords) {
    if ('predictions' in record || 'abstained' in record) {
      throw new Error('Provide labels only; saved predictions are not inference inputs');
    }
  }
  const dataset = parseTtpEvaluationDataset(JSON.stringify({
    ...parsed.labels,
    records: rawRecords.map(record => ({ ...record, abstained: true, predictions: [], abstentionReason: 'pending inference' })),
  }), 'json');
  const started = performance.now();
  for (let offset = 0; offset < dataset.records.length; offset += 128) {
    const records = dataset.records.slice(offset, offset + 128);
    const matches = await client.matchSteps(records.map(record => record.attackStep), {
      embeddingsModel: parsed.model, frameworks: parsed.frameworks, minSimilarity: 0.3, topK: 3,
    });
    const byText = new Map(matches.map(match => [match.attack_step, match.matches]));
    for (const record of records) {
      if (!byText.has(record.attackStep)) throw new Error(`Mapper omitted a result for ${record.id}`);
      const candidates = byText.get(record.attackStep)!;
      const decision = selectTtpDecision({
        attack_step_id: record.id, attack_step_description: record.attackStep,
        top_k: candidates.map((match, index) => ({
          technique_id: match.technique_id, technique_name: match.name,
          similarity_score: match.similarity, framework: match.framework, rank: index + 1,
        })),
      }, CLOUD_TTP_BLOCKLIST);
      record.abstained = decision.abstained;
      if (decision.abstained) record.abstentionReason = decision.abstention_reason;
      else delete record.abstentionReason;
      const ordered = decision.abstained ? candidates : [
        ...candidates.filter(match => match.technique_id === decision.technique_id && match.framework === decision.framework),
        ...candidates.filter(match => match.technique_id !== decision.technique_id || match.framework !== decision.framework),
      ];
      record.predictions = ordered.map((match, index) => ({
        rank: index + 1, techniqueId: match.technique_id,
        similarity: Math.max(0, Math.min(1, match.similarity)),
        modelConfidence: index === 0 ? decision.calibrated_confidence : Math.max(0, Math.min(1, match.similarity)),
      }));
    }
  }
  const verified = parseTtpEvaluationDataset(JSON.stringify(dataset), 'json');
  const report = evaluateTtpQuality(verified);
  return {
    provenance: {
      inference_performed: true,
      generated_at: new Date().toISOString(),
      elapsed_ms: Math.round(performance.now() - started),
      model: parsed.model, frameworks: parsed.frameworks,
      deployment_revision: 'not_verified_by_service',
      labels_sha256: createHash('sha256').update(JSON.stringify(parsed.labels)).digest('hex'),
      review: parsed.review,
      confidence_kind: 'heuristic',
      policy: TTP_ACCEPTANCE_POLICY_VERSION,
      accuracy_acceptance_eligible: false,
      limitation: 'Release accuracy acceptance requires independently reviewed labels and a verified pinned service/model/framework revision. ECE here describes a heuristic score, not a fitted calibration model.',
    },
    dataset: verified,
    report,
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const [, , input, output] = process.argv;
  if (!input || !output) throw new Error('Usage: infer-ttp.ts <labels-and-model.json> <evaluation-output.json>');
  const result = await inferTtpEvaluation(JSON.parse(await readFile(input, 'utf8')));
  await writeFile(output, `${JSON.stringify(result, null, 2)}\n`, { flag: 'wx' });
  console.info(`Evaluated ${result.dataset.records.length} current predictions. Review status: ${result.provenance.review.status}.`);
}
